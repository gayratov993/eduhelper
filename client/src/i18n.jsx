const STORAGE_KEY = 'planeri-lang'
let current = 'uz'
if (typeof localStorage !== 'undefined') {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && DICT[saved]) current = saved
}

export function langCode() {
  return current
}

export function setLangCode(code) {
  if (!DICT[code]) return
  current = code
  try {
    localStorage.setItem(STORAGE_KEY, code)
  } catch {
    /* noop */
  }
}

export function t(key, vars) {
  let str = DICT[current]?.[key] ?? DICT.uz[key] ?? key
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replaceAll(`{${k}}`, String(vars[k]))
    }
  }
  return str
}

const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(current)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  function change(code) {
    setLangCode(code)
    setLang(code)
  }

  return <LangContext.Provider value={{ lang, setLang: change }}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang LangProvider ichida ishlatilishi kerak')
  return ctx
}